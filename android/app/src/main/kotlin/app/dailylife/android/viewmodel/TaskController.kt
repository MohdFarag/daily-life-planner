package app.dailylife.android.viewmodel

import app.dailylife.core.model.RelativeRule
import app.dailylife.core.model.SessionState
import app.dailylife.core.model.Task
import app.dailylife.core.model.TaskSession
import app.dailylife.core.model.TaskStatus
import java.time.Instant
import kotlinx.coroutines.launch

/** Tasks and their execution sessions (TSK01, SES01, REL01). */
class TaskController(private val ctx: ControllerScope, private val focus: FocusController) {

    fun save(task: Task) = ctx.scope.launch { ctx.repository.saveTask(task) }

    fun add(title: String, listId: String) =
        ctx.scope.launch {
            ctx.repository.saveTask(
                Task(id = ctx.newId(), title = title, listId = listId, createdAt = ctx.now())
            )
        }

    /**
     * Completion only follows an explicit tap; completing ends a running focus session on it
     * (§6.3).
     */
    fun toggleDone(task: Task) =
        ctx.scope.launch {
            val completing = task.status != TaskStatus.COMPLETED
            ctx.repository.saveTask(
                task.copy(
                    status = if (completing) TaskStatus.COMPLETED else TaskStatus.NEEDS_ACTION,
                    completedAt = if (completing) ctx.now() else null,
                )
            )
            if (completing && ctx.snapshot.focus?.taskId == task.id) focus.end()
        }

    fun delete(task: Task) =
        ctx.scope.launch {
            ctx.repository.deleteTask(task.id)
            ctx.navigator.back()
        }

    // Sessions -----------------------------------------------------------------------------

    /**
     * Saves a fixed-time session. Editing an occurrence generated by a rule pins it, so later
     * recalculation keeps the user's time for that day (REL03).
     */
    fun saveFixedSession(
        taskId: String,
        start: Instant,
        end: Instant,
        editing: TaskSession? = null,
    ) =
        ctx.scope.launch {
            val session =
                editing?.copy(
                    start = start,
                    end = end,
                    pinned = editing.occurrenceDate != null || editing.pinned,
                ) ?: TaskSession(id = ctx.newId(), taskId = taskId, start = start, end = end)
            ctx.repository.saveSessions(listOf(session))
        }

    fun attachRule(taskId: String, rule: RelativeRule) =
        ctx.scope.launch { ctx.container.ruleScheduler.attach(taskId, rule, ctx.today()) }

    fun detachRule(ruleId: String) =
        ctx.scope.launch { ctx.container.ruleScheduler.detach(ruleId, ctx.today()) }

    /**
     * A rule occurrence is canceled rather than deleted, so recalculation does not bring it back.
     */
    fun deleteSession(session: TaskSession) =
        ctx.scope.launch {
            if (session.occurrenceDate != null)
                ctx.repository.saveSessions(listOf(session.copy(state = SessionState.CANCELED)))
            else ctx.repository.deleteSession(session.id)
        }
}
